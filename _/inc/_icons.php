/** Echo-ready SVG. $stroke = stroke width (reference uses 1.8 for most icons). */
function nundia_icon($name, $class = 'h-4 w-4', $stroke = 1.8) {
    $paths = nundia_icon_paths();
    if (!isset($paths[$name])) return '';
    return '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' . esc_attr($stroke) . '" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-' . esc_attr($name) . ' ' . esc_attr($class) . '" aria-hidden="true">' . $paths[$name] . '</svg>';
}
